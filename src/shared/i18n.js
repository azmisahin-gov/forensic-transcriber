  const LOCALES = Object.freeze({ tr: TR, en: EN });
  const DEFAULT_LOCALE = 'tr';

  function normalize(locale) {
    return Object.prototype.hasOwnProperty.call(LOCALES, locale) ? locale : DEFAULT_LOCALE;
  }

  /**
   * Translate a key. Falls back to Turkish, then to the key itself so a missing
   * string is visible rather than blank. `{name}` placeholders are substituted
   * from `vars`.
   */
  function translate(locale, key, vars) {
    const table = LOCALES[normalize(locale)];
    let value = table[key];
    if (value === undefined) value = TR[key];
    if (value === undefined) return key;
    if (vars) {
      value = value.replace(/\{(\w+)\}/g, (m, name) => (vars[name] !== undefined ? String(vars[name]) : m));
    }
    return value;
  }

  return {
    LOCALES,
    DEFAULT_LOCALE,
    LOCALE_VALUES: Object.keys(LOCALES),
    normalize,
    translate,
  };
